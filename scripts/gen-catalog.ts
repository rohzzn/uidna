/**
 * Generates `docs/tools.md` from `src/contracts/`. Never hand-edit the output.
 * `--check` exits non-zero when the committed file is stale.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { CLI_ONLY_COMMANDS, TOOL_CATALOG } from '../src/contracts/index.js';
import type { ToolContract } from '../src/contracts/index.js';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(repoRoot, 'docs', 'tools.md');

interface JsonSchemaLike {
  type?: string | string[];
  properties?: Record<string, JsonSchemaLike>;
  required?: string[];
  description?: string;
  enum?: unknown[];
  items?: JsonSchemaLike;
  anyOf?: JsonSchemaLike[];
  oneOf?: JsonSchemaLike[];
  const?: unknown;
  format?: string;
  nullable?: boolean;
}

function toJson(schema: z.ZodType): JsonSchemaLike {
  return z.toJSONSchema(schema, { target: 'draft-2020-12', unrepresentable: 'any', io: 'input' }) as JsonSchemaLike;
}

function typeOf(prop: JsonSchemaLike): string {
  if (prop.const !== undefined) return JSON.stringify(prop.const);
  if (prop.enum) return prop.enum.map((v) => JSON.stringify(v)).join(' \\| ');
  const variants = prop.anyOf ?? prop.oneOf;
  if (variants) {
    const parts = variants.map(typeOf).filter((p, i, arr) => arr.indexOf(p) === i);
    return parts.join(' \\| ');
  }
  const type = Array.isArray(prop.type) ? prop.type.join(' \\| ') : prop.type;
  if (type === 'array') return `array of ${prop.items ? typeOf(prop.items) : 'unknown'}`;
  if (type === 'object' && prop.properties) return 'object';
  return type ?? 'unknown';
}

function renderInput(contract: ToolContract): string {
  const schema = toJson(contract.input);
  const required = new Set(schema.required ?? []);
  const rows = Object.entries(schema.properties ?? {}).map(([name, prop]) => {
    const req = required.has(name) ? 'yes' : 'no';
    const desc = (prop.description ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
    return `| \`${name}\` | ${typeOf(prop)} | ${req} | ${desc} |`;
  });
  if (rows.length === 0) return '_No inputs._\n';
  return ['| Field | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows].join('\n') + '\n';
}

function renderOutput(contract: ToolContract): string {
  const schema = toJson(contract.output);
  const keys = Object.keys(schema.properties ?? {});
  if (keys.length === 0) return '_See schema._\n';
  return keys.map((k) => `\`${k}\``).join(', ') + '\n';
}

function renderTool(contract: ToolContract): string {
  const a = contract.annotations;
  const flags = [
    a.readOnlyHint ? 'read-only' : 'writes artifacts',
    a.destructiveHint ? 'destructive' : 'non-destructive',
    a.idempotentHint ? 'idempotent' : 'not idempotent',
    a.openWorldHint ? 'reaches the network' : 'local only',
  ].join(', ');
  return [
    `### \`${contract.name}\``,
    '',
    `**${contract.title}** — shape: \`${contract.shape}\` — CLI: \`uidna ${contract.cli.command}${contract.cli.positionals.map((p) => ` <${p}>`).join('')}\``,
    '',
    contract.description,
    '',
    `Effects: ${flags}. ${contract.longRunning ? 'Long-running: accepts progress tokens and cancellation.' : 'Returns immediately.'}`,
    '',
    '**Input**',
    '',
    renderInput(contract),
    '**Result fields**',
    '',
    renderOutput(contract),
  ].join('\n');
}

function render(): string {
  const header = [
    '<!-- Generated by scripts/gen-catalog.ts from src/contracts/. Do not edit by hand. -->',
    '# Tool catalog',
    '',
    'Every tool returns the same evidence envelope:',
    '',
    '```json',
    '{ "result": {}, "evidence_id": "ev_…", "evidence": { "kind": "…", "inputs": {}, "artifacts": [], "capturedAt": "…" }, "limitations": [], "unknowns": [] }',
    '```',
    '',
    'Results are complete by default; any truncation says why and how to get the rest. Observed, measured, inferred and unknown stay distinct. Large artifacts are referenced by path, never inlined.',
    '',
    '| Tool | Shape | CLI |',
    '| --- | --- | --- |',
    ...TOOL_CATALOG.map((t) => `| \`${t.name}\` | ${t.shape} | \`uidna ${t.cli.command}\` |`),
    ...CLI_ONLY_COMMANDS.map((c) => `| _(CLI only)_ | workflow | \`uidna ${c.command}\` — ${c.summary} |`),
    '',
  ];
  return header.join('\n') + '\n' + TOOL_CATALOG.map(renderTool).join('\n');
}

const content = render();
if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = await readFile(outPath, 'utf8');
  } catch {
    existing = '';
  }
  if (existing !== content) {
    console.error(`docs/tools.md is stale. Run: npm run docs:catalog`);
    process.exit(1);
  }
  console.log('docs/tools.md is up to date');
} else {
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, content, 'utf8');
  console.log(`wrote ${outPath}`);
}
