/**
 * Playwright behavior tests for the generated project: one test per recorded
 * transition the generator implemented (deduplicated per target, action and
 * viewport), a `test.skip` with the reason for every other transition. Tests
 * locate the target by role and exact accessible name, fall back to the
 * `data-uidna-path` attribute, perform the recorded action and assert the
 * observed delta. Page text only ever reaches the file as JS string literals.
 */
import type { BehaviorReport, Expectation, LocatorSpec, TestStep, TransitionTest } from './behavior.js';
import { commentText, jsString } from './jsx.js';

/** Default port of `vite preview` in the generated project. */
export const BEHAVIOR_TEST_PORT = 4173;

/** `playwright.config.ts` content. */
export function renderPlaywrightConfig(): string {
  return [
    '// Generated by UI DNA: runs the behavior tests in tests/ against `vite preview` of the built project.',
    "import { defineConfig } from '@playwright/test';",
    '',
    `const port = Number(process.env.PORT ?? ${BEHAVIOR_TEST_PORT});`,
    'const baseURL = process.env.BASE_URL ?? `http://127.0.0.1:${port}`;',
    '',
    'export default defineConfig({',
    "  testDir: 'tests',",
    '  fullyParallel: false,',
    "  reporter: 'list',",
    '  use: { baseURL },',
    '  webServer: {',
    '    command: `npm run preview -- --host 127.0.0.1 --port ${port} --strictPort`,',
    '    url: baseURL,',
    '    reuseExistingServer: true,',
    '    timeout: 60_000,',
    '  },',
    '});',
    '',
  ].join('\n');
}

function pathLocator(path: string): string {
  return `page.locator(${jsString(`[data-uidna-path="${path}"]`)})`;
}

function stepCode(step: TestStep, target: string): string[] {
  switch (step.action) {
    case 'click':
      return [`await ${target}.click();`];
    case 'hover':
      return [`await ${target}.hover();`];
    case 'focus':
      return [`await ${target}.focus();`];
    case 'key':
      return step.locator === null ? [`await page.keyboard.press(${jsString(step.key ?? '')});`] : [`await ${target}.press(${jsString(step.key ?? '')});`];
    case 'fill': {
      const value = step.value ?? '';
      if (step.control === 'select') return [`await ${target}.selectOption(${jsString(value)});`];
      if (step.control === 'checkbox') return [value === 'true' ? `await ${target}.check();` : `await ${target}.uncheck();`];
      return [`await ${target}.fill(${jsString(value)});`];
    }
    case 'submit':
      return [`await submitForm(${target}, ${step.click ? 'true' : 'false'});`];
    default:
      return [];
  }
}

function urlMatcher(pattern: string): string {
  if (!/[:*]/.test(pattern)) return jsString(pattern);
  const escaped = pattern.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/:[A-Za-z0-9_]+/g, '[^/]+').replace(/\*/g, '.*');
  return `new RegExp(${jsString(`${escaped}$`)})`;
}

function expectationCode(expectation: Expectation): string {
  switch (expectation.kind) {
    case 'attribute': {
      const node = pathLocator(expectation.locator.path);
      return expectation.value === null ? `await expect(${node}).not.toHaveAttribute(${jsString(expectation.attribute)});` : `await expect(${node}).toHaveAttribute(${jsString(expectation.attribute)}, ${jsString(expectation.value)});`;
    }
    case 'visible':
      return `await expect(${pathLocator(expectation.locator.path)}).${expectation.visible ? 'toBeVisible' : 'toBeHidden'}();`;
    case 'text':
      return `await expect(${pathLocator(expectation.locator.path)}).${expectation.exact ? 'toHaveText' : 'toContainText'}(${jsString(expectation.text)});`;
    case 'url':
      return `await expect(page).toHaveURL(${urlMatcher(expectation.pattern)});`;
    case 'value': {
      const node = pathLocator(expectation.locator.path);
      if (expectation.control === 'checkbox') return expectation.value === 'true' ? `await expect(${node}).toBeChecked();` : `await expect(${node}).not.toBeChecked();`;
      return `await expect(${node}).toHaveValue(${jsString(expectation.value)});`;
    }
    default:
      return '';
  }
}

function locateCode(locator: LocatorSpec): string {
  return `await locate(page, ${locator.role === null ? 'null' : jsString(locator.role)}, ${locator.name === null ? 'null' : jsString(locator.name)}, ${locator.nth === null ? 'null' : String(locator.nth)}, ${jsString(locator.path)})`;
}

function describeStep(step: TestStep): string {
  const where = step.locator === null ? 'the page' : `${step.locator.role ?? 'node'}${step.locator.name === null ? '' : ` "${step.locator.name}"`} at ${step.locator.path || 'body'}`;
  switch (step.action) {
    case 'key':
      return `key ${step.key ?? '?'} on ${where}`;
    case 'fill':
      return `fill ${where}`;
    default:
      return `${step.action} ${where}`;
  }
}

function testBody(test: TransitionTest): string[] {
  const lines: string[] = [];
  lines.push(`    await page.setViewportSize({ width: ${test.viewport.width}, height: ${test.viewport.height} });`);
  lines.push(`    await page.goto(${jsString(test.route)});`);
  test.setup.forEach((step, index) => {
    const name = `setup${(index + 1).toString().padStart(2, '0')}`;
    lines.push(`    // ${commentText(describeStep(step))}`);
    if (step.locator !== null) lines.push(`    const ${name} = ${locateCode(step.locator)};`);
    for (const code of stepCode(step, name)) lines.push(`    ${code}`);
  });
  if (test.step.locator !== null) lines.push(`    const target = ${locateCode(test.step.locator)};`);
  for (const code of stepCode(test.step, 'target')) lines.push(`    ${code}`);
  if (test.expectations.length === 0) lines.push('    // The scan recorded no attribute, text, visibility or style delta the generator reproduces; the action itself is the assertion.');
  for (const expectation of test.expectations) lines.push(`    ${expectationCode(expectation)}`);
  if (test.revert !== null) {
    // The action may have changed the target's accessible name, so the revert locates it by path.
    lines.push(`    // ${commentText(describeStep(test.revert.step))} restores the previous state`);
    const revertLocator = test.revert.step.locator;
    if (revertLocator !== null) lines.push(`    const reverted = ${pathLocator(revertLocator.path)};`);
    for (const code of stepCode(test.revert.step, 'reverted')) lines.push(`    ${code}`);
    for (const expectation of test.revert.expectations) lines.push(`    ${expectationCode(expectation)}`);
  }
  return lines;
}

/** Which tests the spec file contains, for the README and the manifest. */
export interface BehaviorSpecSummary {
  readonly tests: number;
  readonly skipped: number;
  /** Transition ids that share a test with an earlier transition (same target, action and viewport). */
  readonly deduplicated: readonly string[];
}

/** `tests/behavior.spec.ts` content and its summary. */
export function renderBehaviorSpec(scanId: string, reports: readonly BehaviorReport[]): { code: string; summary: BehaviorSpecSummary } {
  const seen = new Map<string, string>();
  const deduplicated: string[] = [];
  const bodies: string[][] = [];
  let tests = 0;
  let skipped = 0;
  let usesLocate = false;
  let usesSubmit = false;
  for (const report of reports) {
    const title = `${report.transitionId}: ${report.action} ${report.target}`;
    if (report.status !== 'implemented' || report.test === null) {
      skipped += 1;
      bodies.push([`  // ${commentText(report.detail)}`, `  test.skip(${jsString(`${title}: not reproduced`)}, async () => {`, '    // Reason: see the comment above and README "Behavior".', '  });']);
      continue;
    }
    const test = report.test;
    const first = seen.get(test.dedupeKey);
    if (first !== undefined) {
      deduplicated.push(report.transitionId);
      continue;
    }
    seen.set(test.dedupeKey, report.transitionId);
    tests += 1;
    const steps = [...test.setup, test.step, ...(test.revert === null ? [] : [test.revert.step])];
    if (steps.some((s) => s.locator !== null)) usesLocate = true;
    if (steps.some((s) => s.action === 'submit')) usesSubmit = true;
    bodies.push([`  // ${commentText(report.detail)}`, `  test(${jsString(`${title} (${test.viewport.width}×${test.viewport.height})`)}, async ({ page }) => {`, ...testBody(test), '  });']);
  }

  const lines: string[] = [];
  lines.push(`// Generated by UI DNA from scan ${commentText(scanId)}: behavior tests replaying the recorded transitions the generator implemented.`);
  lines.push('// Run `npm run build` first; `npm run test:behavior` starts `vite preview` (see playwright.config.ts) and runs these tests against it.');
  lines.push(`import { expect, test${usesLocate || usesSubmit ? ', type Locator' : ''}${usesLocate ? ', type Page' : ''} } from '@playwright/test';`);
  lines.push('');
  if (usesLocate) {
    lines.push('/** Locate a scanned element by role and exact accessible name (nth match), falling back to its data-uidna-path attribute. */');
    lines.push('async function locate(page: Page, role: string | null, name: string | null, nth: number | null, path: string): Promise<Locator> {');
    lines.push('  if (role !== null) {');
    lines.push('    try {');
    lines.push("      const byRole = page.getByRole(role as Parameters<Page['getByRole']>[0], name === null ? {} : { name, exact: true }).nth(nth ?? 0);");
    lines.push('      if ((await byRole.count()) > 0) return byRole;');
    lines.push('    } catch {');
    lines.push('      // Not a role Playwright knows: fall through to the path locator.');
    lines.push('    }');
    lines.push('  }');
    lines.push('  return page.locator(`[data-uidna-path="${path}"]`);');
    lines.push('}');
    lines.push('');
  }
  if (usesSubmit) {
    lines.push('/**');
    lines.push(' * Submit the form that contains `target` (or `target` itself) as the scan did: by clicking the submit');
    lines.push(' * control, or by requesting submission. The native request is blocked, as it was during the scan, so a');
    lines.push(' * replay never sends anything to the server; the generated onSubmit handler still runs.');
    lines.push(' */');
    lines.push('async function submitForm(target: Locator, click: boolean): Promise<void> {');
    lines.push('  await target.evaluate((element) => {');
    lines.push("    const form = element instanceof HTMLFormElement ? element : element.closest('form');");
    lines.push("    form?.addEventListener('submit', (event) => { event.preventDefault(); }, { once: true });");
    lines.push('  });');
    lines.push('  if (click) {');
    lines.push('    await target.click();');
    lines.push('    return;');
    lines.push('  }');
    lines.push('  await target.evaluate((element) => {');
    lines.push("    const form = element instanceof HTMLFormElement ? element : element.closest('form');");
    lines.push('    if (form) form.requestSubmit();');
    lines.push('  });');
    lines.push('}');
    lines.push('');
  }
  lines.push(`test.describe(${jsString(`transitions recorded by scan ${scanId}`)}, () => {`);
  if (bodies.length === 0) {
    lines.push("  test.skip('no transition was recorded', async () => {");
    lines.push('    // Run explore_interactions on the scan and regenerate to get behavior tests.');
    lines.push('  });');
  }
  bodies.forEach((body, index) => {
    if (index > 0) lines.push('');
    lines.push(...body);
  });
  lines.push('});');
  lines.push('');
  return { code: lines.join('\n'), summary: { tests, skipped, deduplicated } };
}
